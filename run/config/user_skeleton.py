"""Single source of truth for the durable user-directory skeleton.

The skeleton is deliberately limited to directories.  Runtime databases,
preferences, uploaded media, and background-job artifacts are created by their
owning subsystems. The default background.webp is a static template asset copied
only when creating a user; directory repair never adds or replaces it.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
import stat
from collections.abc import MutableSequence


_LOGGER = logging.getLogger(__name__)
_REPARSE_POINT = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)

# Keep this tuple ordered: reports and tests use the stable order when showing
# what was created during a repair.
REQUIRED_USER_DIRS = (
    "agents",
    "avatar",
    "download",
    "expand",
    "file_upload",
    "history",
    "improve",
    "improve/expired_memory",
    "knowledge",
    "task_cron",
    "task_plan",
    "user_skills",
    "user_skills/agent_create",
    "user_skills/user_create",
    "runtime",
    "tools",
)

# These paths are generated by their owning runtime subsystem.  They are
# documented here so template, migration, and validation code share the same
# classification without pre-creating runtime data in the template.
RUNTIME_GENERATED_DIRS = (
    "runtime/background_jobs",
    "history/thumbnails",
)

OPTIONAL_USER_FILES = ("web_preferences.json",)
TEMPLATE_BACKGROUND_FILE = "background.webp"
SOUND_FILE_PREFIXES = ("completion_sound.", "failure_sound.")
TEMPLATE_ONLY_EMPTY_DIRS = ("runtime", "tools")


def _is_reparse_point(path: Path) -> bool:
    """Return whether *path* is a symlink or Windows reparse point.

    Inspection failures are treated as unsafe.  This function is intentionally
    local instead of importing the background-job implementation so the config
    package remains dependency-light and has no runtime-job coupling.
    """

    try:
        info = os.lstat(path)
    except FileNotFoundError:
        return False
    except OSError:
        return True
    return bool(stat.S_ISLNK(info.st_mode)) or bool(
        getattr(info, "st_file_attributes", 0) & _REPARSE_POINT
    )


def _contains_reparse_point(path: Path, base: Path) -> bool:
    """Check *path* and every existing parent up to *base*."""

    current = path
    try:
        while True:
            if _is_reparse_point(current):
                return True
            if current == base:
                return False
            if base not in current.parents:
                return True
            current = current.parent
    except OSError:
        return True


def _record_issue(
    relative: str,
    *,
    issues: MutableSequence[str] | None,
    reason: str,
) -> None:
    if issues is not None and relative not in issues:
        issues.append(relative)
    _LOGGER.warning("用户目录骨架未能处理 %s：%s", relative, reason)


def inspect_user_skeleton(user_dir: Path) -> tuple[list[str], list[str]]:
    """Return ``(missing, unsafe_or_invalid)`` without changing the filesystem."""

    base = Path(user_dir)
    if not base.is_dir() or _is_reparse_point(base):
        return [], ["."]

    missing: list[str] = []
    issues: list[str] = []
    for relative in REQUIRED_USER_DIRS:
        target = base / relative
        if _contains_reparse_point(target, base):
            issues.append(relative)
        elif not target.exists():
            missing.append(relative)
        elif not target.is_dir():
            issues.append(relative)
    return missing, issues


def ensure_user_skeleton(
    user_dir: Path,
    *,
    issues: MutableSequence[str] | None = None,
) -> list[str]:
    """Idempotently create missing required directories below one real user.

    Only ``mkdir(parents=True, exist_ok=True)`` is used.  Existing files,
    symlinks, junctions, and paths whose parents redirect are never replaced,
    followed, or deleted.  The return value contains only directories created
    during this call.  Unsafe or invalid paths are skipped and optionally
    appended to ``issues``; callers can decide whether to warn or fail.
    """

    base = Path(user_dir)
    if base.name == "user" and base.parent.name == "template":
        _record_issue(
            ".",
            issues=issues,
            reason="补齐函数不能作用于 template/user",
        )
        return []
    if not base.is_dir() or _is_reparse_point(base):
        _record_issue(
            ".",
            issues=issues,
            reason="用户目录不存在、不是目录或是符号链接/目录联接",
        )
        return []

    created: list[str] = []
    for relative in REQUIRED_USER_DIRS:
        target = base / relative
        if _contains_reparse_point(target, base):
            _record_issue(
                relative,
                issues=issues,
                reason="路径包含符号链接或目录联接",
            )
            continue
        try:
            if target.exists():
                if not target.is_dir():
                    _record_issue(
                        relative,
                        issues=issues,
                        reason="目标已存在但不是目录",
                    )
                continue
            target.mkdir(parents=True, exist_ok=True)
            # Re-check after mkdir to avoid reporting a path that was swapped
            # by another process during a race.
            if _contains_reparse_point(target, base) or not target.is_dir():
                _record_issue(
                    relative,
                    issues=issues,
                    reason="创建后路径不再是安全目录",
                )
                continue
            created.append(relative)
        except OSError as exc:
            _record_issue(relative, issues=issues, reason=str(exc))
    return created


